#!/usr/bin/env python3
"""Generate the Crate Decks theme files from res/crate-design/tokens.json.

Standard library only. Reads the tokens and writes, under
res/crate-design/generated/:

* every template in tools/crate-design/templates/ (``<name>.<ext>.in``),
  with ``{{token}}`` and ``{{token.filter}}`` placeholders replaced;
* each Solar icon (svg/solar/) and base control (svg/controls/) once per
  icon state, with ``currentColor`` replaced by the state colour;
* the knob and fader scales and the fader handles, drawn from the geometry
  tokens.

It fails if a template uses a token that does not exist, or if a token is
used by nobody. With --check it writes to a temporary directory and fails
if the result differs from what is committed.
"""

import argparse
import json
import math
import re
import shutil
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from xml.sax.saxutils import escape

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
TOKENS = REPO / "res" / "crate-design" / "tokens.json"
TEMPLATES = HERE / "templates"
SVG = HERE / "svg"
OUT = REPO / "res" / "crate-design" / "generated"

MARKER = "GENERATED"
MARKER_TEXT = (
    "Generated by tools/crate-design/generate.py from "
    "res/crate-design/tokens.json. Do not edit by hand.\n"
)
NAME_RE = re.compile(r"^[a-z][A-Za-z0-9]*$")
HEX_RE = re.compile(r"^#[0-9a-f]{6}$")
PLACEHOLDER_RE = re.compile(r"\{\{\s*([A-Za-z0-9_.]+)\s*\}\}")
SELECTOR_RE = re.compile(r"\{([A-Za-z0-9]+)\}")
FORMATS = ("qss", "xml", "qml", "svg")
FILTERS = ("hex", "alpha", "argb", "rgba", "number", "list", "unit")

# Icon states, in output order, and the token that colours each one.
STATES = {
    "idle": "iconIdle",
    "hover": "iconHover",
    "active": "iconActive",
    "disabled": "iconDisabled",
    "onaccent": "iconOnAccent",
}


class GeneratorError(Exception):
    """One or more problems with the tokens or the templates."""

    def __init__(self, problems):
        self.problems = list(problems)
        super().__init__("\n".join(self.problems))


@dataclass(frozen=True)
class Token:
    name: str
    group: str
    value: object
    unit: str = ""
    alpha: float = None
    pending: str = None

    @property
    def is_colour(self):
        return isinstance(self.value, str) and HEX_RE.match(self.value)


def number(value):
    """Shortest exact text for a token number: 1, 1.25, 0.1."""
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise TypeError(value)
    if float(value).is_integer():
        return str(int(value))
    return repr(float(value))


def raw_tokens(data):
    """Return ({name: (group, entry)}, problems) for the tokens of data."""
    problems = []
    raw = {}
    for group, entries in data["tokens"].items():
        for name, entry in entries.items():
            if not NAME_RE.match(name):
                problems.append(f"{name}: names are lowerCamelCase")
            if name in raw:
                problems.append(
                    f"{name}: defined in {raw[name][0]} and {group}"
                )
            raw[name] = (group, entry)
    return raw, problems


def expand_ref(name, ref, raw):
    """Return (target, selectors) for a ref.

    A ref may name a palette switch: in "waveLow{wavePaletteDeckAC}" the
    braces take the text value of that token ("Accent" or "Neutral"), so one
    token picks the palette of several refs.
    """
    selectors = SELECTOR_RE.findall(ref)
    for selector in selectors:
        entry = raw.get(selector, (None, {}))[1]
        value = entry.get("value")
        if selector not in raw or "ref" in entry or not isinstance(value, str):
            raise GeneratorError(
                [f"{name}: {{{selector}}} must name a token with a text value"]
            )
    target = SELECTOR_RE.sub(lambda m: raw[m.group(1)][1]["value"], ref)
    return target, selectors


def load_tokens(path):
    """Read tokens.json and return {name: Token} with refs resolved."""
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    raw, problems = raw_tokens(data)

    def resolve(name, seen):
        group, entry = raw[name]
        if "ref" in entry:
            target, _ = expand_ref(name, entry["ref"], raw)
            if target not in raw:
                raise GeneratorError(
                    [f"{name}: ref to unknown token {target}"]
                )
            if target in seen:
                raise GeneratorError([f"{name}: circular ref"])
            base = resolve(target, seen | {name})
            return Token(
                name,
                group,
                base.value,
                base.unit,
                base.alpha,
                entry.get("pending"),
            )
        value = entry.get("value")
        alpha = entry.get("alpha")
        if isinstance(value, str) and value.startswith("#"):
            if not HEX_RE.match(value):
                problems.append(f"{name}: colours are #rrggbb in lower case")
        if alpha is not None and not 0 <= alpha <= 1:
            problems.append(f"{name}: alpha must be between 0 and 1")
        if value is None:
            problems.append(f"{name}: needs a value or a ref")
        return Token(
            name,
            group,
            value,
            entry.get("unit", ""),
            alpha,
            entry.get("pending"),
        )

    tokens = {}
    for name in raw:
        try:
            tokens[name] = resolve(name, frozenset())
        except GeneratorError as error:
            problems.extend(error.problems)
    if problems:
        raise GeneratorError(list(dict.fromkeys(problems)))
    return tokens


def ref_graph(path):
    """Return {name: (target, selectors)} for the tokens that are refs."""
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    raw, _ = raw_tokens(data)
    return {
        name: expand_ref(name, entry["ref"], raw)
        for name, (_, entry) in raw.items()
        if "ref" in entry
    }


def refs(path):
    """Return {name: referenced token name} for the tokens that are refs."""
    return {name: target for name, (target, _) in ref_graph(path).items()}


def rgb(token):
    value = token.value
    return tuple(int(value[i : i + 2], 16) for i in (1, 3, 5))


def alpha_byte(token):
    return round((1.0 if token.alpha is None else token.alpha) * 255)


def apply_filter(token, name, where):
    """Format a token for an explicit {{token.filter}} placeholder."""
    if name in ("hex", "alpha", "argb", "rgba") and not token.is_colour:
        raise GeneratorError([f"{where}: {token.name} is not a colour"])
    if name == "hex":
        return token.value
    if name == "alpha":
        return number(1 if token.alpha is None else token.alpha)
    if name == "argb":
        return "#%02x%s" % (alpha_byte(token), token.value[1:])
    if name == "rgba":
        r, g, b = rgb(token)
        return f"rgba({r}, {g}, {b}, {alpha_byte(token)})"
    if name == "number":
        return number(token.value)
    if name == "unit":
        return token.unit
    if name == "list":
        return ", ".join(str(token.value).split())
    raise GeneratorError([f"{where}: unknown filter .{name}"])


def format_token(token, fmt):
    """Format a token for a bare {{token}} in a file of format fmt."""
    value = token.value
    if token.is_colour:
        if token.alpha is None:
            return value
        if fmt == "qss":
            return apply_filter(token, "rgba", "")
        if fmt == "svg":
            raise GeneratorError(
                [f"{token.name} has alpha: use its .hex and .alpha in SVG"]
            )
        return apply_filter(token, "argb", "")
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        if fmt == "qss" and token.unit in ("px", "em"):
            return number(value) + token.unit
        return number(value)
    text = str(value)
    return escape(text) if fmt in ("xml", "svg") else text


def render(text, fmt, tokens, used, origin):
    """Replace the placeholders of one template; record the tokens used."""
    problems = []

    def substitute(match, line_number):
        name, _, flt = match.group(1).partition(".")
        where = f"{origin}:{line_number}"
        token = tokens.get(name)
        if token is None:
            problems.append(f"{where}: unknown token {name}")
            return match.group(0)
        used.add(name)
        try:
            if flt:
                return apply_filter(token, flt, where)
            return format_token(token, fmt)
        except GeneratorError as error:
            problems.extend(f"{where}: {p}" for p in error.problems)
            return match.group(0)

    lines = []
    for line_number, line in enumerate(text.split("\n"), 1):
        lines.append(
            PLACEHOLDER_RE.sub(lambda m: substitute(m, line_number), line)
        )
    if problems:
        raise GeneratorError(problems)
    return "\n".join(lines)


def template_format(path):
    fmt = path.name[: -len(".in")].rsplit(".", 1)[-1]
    if fmt not in FORMATS:
        raise GeneratorError([f"{path}: unknown template format .{fmt}"])
    return fmt


def recolour(svg_text, colour):
    """Paint an icon or base control: currentColor becomes the colour."""
    return svg_text.replace("currentColor", colour)


def stroke_line(x1, y1, x2, y2, colour, width, extra=""):
    return (
        f'<line x1="{x1:.2f}" y1="{y1:.2f}" x2="{x2:.2f}" y2="{y2:.2f}" '
        f'stroke="{colour}" stroke-width="{width}"{extra}/>'
    )


def svg_document(width, height, body):
    head = (
        '<svg xmlns="http://www.w3.org/2000/svg" '
        f'width="{number(width)}" height="{number(height)}" '
        f'viewBox="0 0 {number(width)} {number(height)}">'
    )
    return "\n".join([head, *("  " + line for line in body), "</svg>", ""])


def knob_scale(t, used):
    """Knob background: hairline ring and ticks over the knob's sweep."""
    names = (
        "knobSize",
        "knobSweep",
        "knobTickCount",
        "knobTickEvery",
        "knobTickLong",
        "knobTickShort",
        "strokeHairline",
        "border",
        "borderHover",
        "textFaint",
    )
    used.update(names)
    size = t["knobSize"].value
    centre = size / 2
    ring = centre - 0.5 - t["knobTickLong"].value - 1.5
    width = number(t["strokeHairline"].value)
    half_sweep = t["knobSweep"].value / 2
    step = 360 / t["knobTickCount"].value
    body = [
        f'<circle cx="{number(centre)}" cy="{number(centre)}" '
        f'r="{ring:.2f}" fill="none" stroke="{t["border"].value}" '
        f'stroke-opacity="{number(t["border"].alpha)}" '
        f'stroke-width="{width}"/>'
    ]
    count = int(half_sweep // step)
    for k in range(-count, count + 1):
        angle = math.radians(k * step - 90)
        is_long = k % t["knobTickEvery"].value == 0
        length = t["knobTickLong" if is_long else "knobTickShort"].value
        colour = t["textFaint" if is_long else "borderHover"]
        opacity = "" if colour.alpha is None else number(colour.alpha)
        start = ring + 1.5
        body.append(
            stroke_line(
                centre + math.cos(angle) * start,
                centre + math.sin(angle) * start,
                centre + math.cos(angle) * (start + length),
                centre + math.sin(angle) * (start + length),
                colour.value,
                width,
                f' stroke-opacity="{opacity}"' if opacity else "",
            )
        )
    return svg_document(size, size, body)


def fader_scale(t, used, vertical, length=120):
    """Fader background: 1 px rail with ticks every faderTickStep percent."""
    names = (
        "faderRail",
        "faderTickStep",
        "faderHandleWidth",
        "tickLong",
        "tickShort",
        "strokeHairline",
        "borderHover",
        "textFaint",
        "textMuted",
    )
    used.update(names)
    across = t["faderHandleWidth"].value + 2 * t["tickLong"].value
    middle = across / 2
    rail = number(t["faderRail"].value)
    width = number(t["strokeHairline"].value)
    rail_colour = t["borderHover"]
    rail_opacity = f' stroke-opacity="{number(rail_colour.alpha)}"'
    steps = int(100 // t["faderTickStep"].value)
    handle_half = t["faderHandleWidth"].value / 2
    body = []
    if vertical:
        body.append(
            stroke_line(
                middle,
                0,
                middle,
                length,
                rail_colour.value,
                rail,
                rail_opacity,
            )
        )
    else:
        body.append(
            stroke_line(
                0,
                middle,
                length,
                middle,
                rail_colour.value,
                rail,
                rail_opacity,
            )
        )
    for i in range(steps + 1):
        position = 0.5 + (length - 1) * i / steps
        centre_tick = 2 * i == steps
        size = t["tickLong"].value if centre_tick else t["tickShort"].value
        tick_colour = t["textMuted" if centre_tick else "textFaint"].value
        for side in (-1, 1):
            a = middle + side * handle_half
            b = a + side * size
            if vertical:
                body.append(
                    stroke_line(a, position, b, position, tick_colour, width)
                )
            else:
                body.append(
                    stroke_line(position, a, position, b, tick_colour, width)
                )
    if vertical:
        return svg_document(across, length, body)
    return svg_document(length, across, body)


def fader_handle(t, used, vertical, state):
    """Outline handle; filled with the active colour when active."""
    names = (
        "faderHandleWidth",
        "faderHandleHeight",
        "strokeHairline",
        "radiusSm",
        "bgApp",
        "textPrimary",
        STATES[state],
    )
    used.update(names)
    long_side = t["faderHandleWidth"].value
    short_side = t["faderHandleHeight"].value
    width, height = (
        (long_side, short_side) if vertical else (short_side, long_side)
    )
    colour = t[STATES[state]].value
    fill = colour if state == "active" else t["bgApp"].value
    stroke = number(t["strokeHairline"].value)
    inset = t["strokeHairline"].value / 2
    body = [
        f'<rect x="{number(inset)}" y="{number(inset)}" '
        f'width="{number(width - 2 * inset)}" '
        f'height="{number(height - 2 * inset)}" '
        f'rx="{number(t["radiusSm"].value)}" fill="{fill}" '
        f'stroke="{colour}" stroke-width="{stroke}"/>',
        stroke_line(
            *(
                (width * 0.25, height / 2, width * 0.75, height / 2)
                if vertical
                else (width / 2, height * 0.25, width / 2, height * 0.75)
            ),
            t["bgApp"].value if state == "active" else t["textPrimary"].value,
            stroke,
        ),
    ]
    return svg_document(width, height, body)


def build(tokens_path, templates_dir, svg_dir, out_dir):
    """Write every output under out_dir, which must be empty or absent."""
    tokens = load_tokens(tokens_path)
    used = set()
    outputs = {}
    problems = []

    for template in sorted(templates_dir.rglob("*.in")):
        relative = template.relative_to(templates_dir)
        try:
            text = render(
                template.read_text(encoding="utf-8"),
                template_format(template),
                tokens,
                used,
                relative,
            )
        except GeneratorError as error:
            problems.extend(error.problems)
            continue
        outputs[relative.with_name(relative.name[: -len(".in")])] = text

    used.update(STATES.values())
    for kind, target in (("solar", "icons"), ("controls", "controls")):
        source_dir = svg_dir / kind
        sources = sorted(source_dir.glob("*.svg")) + sorted(
            source_dir.glob("*.svg.in")
        )
        for source in sources:
            text = source.read_text(encoding="utf-8")
            stem = source.name.split(".svg")[0]
            if source.name.endswith(".in"):
                try:
                    text = render(text, "svg", tokens, used, source.name)
                except GeneratorError as error:
                    problems.extend(error.problems)
                    continue
            if "currentColor" not in text:
                problems.append(f"{source}: no currentColor to recolour")
                continue
            for state, token_name in STATES.items():
                name = Path(target) / f"{stem}_{state}.svg"
                outputs[name] = recolour(text, tokens[token_name].value)

    controls = Path("controls")
    outputs[controls / "knob-scale.svg"] = knob_scale(tokens, used)
    outputs[controls / "fader-scale-v.svg"] = fader_scale(tokens, used, True)
    outputs[controls / "fader-scale-h.svg"] = fader_scale(tokens, used, False)
    for state in STATES:
        for vertical, suffix in ((True, "v"), (False, "h")):
            outputs[controls / f"fader-handle-{suffix}_{state}.svg"] = (
                fader_handle(tokens, used, vertical, state)
            )

    # A ref uses the token it points to and the palette switch it names
    graph = ref_graph(tokens_path)
    pending = list(used)
    while pending:
        target, selectors = graph.get(pending.pop(), (None, []))
        for name in ([target] if target else []) + selectors:
            if name not in used:
                used.add(name)
                pending.append(name)
    unused = sorted(set(tokens) - used)
    for name in unused:
        problems.append(f"{name}: token is not used by any template or SVG")
    if problems:
        raise GeneratorError(problems)

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / MARKER).write_text(MARKER_TEXT, encoding="utf-8")
    for relative, text in outputs.items():
        target = out_dir / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        if not text.endswith("\n"):
            text += "\n"
        target.write_text(text, encoding="utf-8")
    return sorted(outputs)


def tree(directory):
    return {
        p.relative_to(directory): p.read_bytes()
        for p in sorted(directory.rglob("*"))
        if p.is_file()
    }


def differences(expected_dir, actual_dir):
    """Paths that differ between two output trees."""
    expected = tree(expected_dir)
    actual = tree(actual_dir) if actual_dir.exists() else {}
    changed = [
        f"changed: {path}"
        for path in expected
        if path in actual and expected[path] != actual[path]
    ]
    missing = [f"missing: {path}" for path in expected if path not in actual]
    extra = [f"stale: {path}" for path in actual if path not in expected]
    return changed + missing + extra


def generate(tokens_path, templates_dir, svg_dir, out_dir, check=False):
    """Regenerate out_dir, or with check compare it; returns problems."""
    with tempfile.TemporaryDirectory() as scratch:
        fresh = Path(scratch) / "generated"
        build(tokens_path, templates_dir, svg_dir, fresh)
        if check:
            return differences(fresh, out_dir)
        if out_dir.exists():
            if any(out_dir.iterdir()) and not (out_dir / MARKER).exists():
                raise GeneratorError(
                    [f"{out_dir}: not a generated directory, not replacing"]
                )
            shutil.rmtree(out_dir)
        shutil.copytree(fresh, out_dir)
    return []


def main(argv=None):
    parser = argparse.ArgumentParser(
        description=__doc__.splitlines()[0],
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the committed output is not up to date",
    )
    parser.add_argument("--tokens", type=Path, default=TOKENS)
    parser.add_argument("--templates", type=Path, default=TEMPLATES)
    parser.add_argument("--svg", type=Path, default=SVG)
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args(argv)
    try:
        problems = generate(
            args.tokens, args.templates, args.svg, args.out, args.check
        )
    except GeneratorError as error:
        for problem in error.problems:
            print(f"error: {problem}", file=sys.stderr)
        return 1
    if problems:
        print(
            "The generated files are out of date; run "
            "tools/crate-design/generate.py:",
            file=sys.stderr,
        )
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
